-- 17. TRIGGERS
CREATE OR REPLACE TRIGGER TRG_CHECK_VE_PHONG
BEFORE INSERT OR UPDATE ON VE
FOR EACH ROW
DECLARE
    v_phong_suat NUMBER;
    v_phong_ghe  NUMBER;
BEGIN
    SELECT MaPhong INTO v_phong_suat FROM SUAT_CHIEU WHERE MaSuat = :NEW.MaSuat;
    SELECT MaPhong INTO v_phong_ghe FROM GHE WHERE MaGhe = :NEW.MaGhe;

    IF v_phong_suat != v_phong_ghe THEN
        RAISE_APPLICATION_ERROR(-20001, 'Lỗi ràng buộc: Ghế không thuộc phòng chiếu của suất chiếu này!');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_CHONG_TRUNG_LICH
BEFORE INSERT OR UPDATE ON SUAT_CHIEU
FOR EACH ROW
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM SUAT_CHIEU
    WHERE MaPhong = :NEW.MaPhong
      AND MaSuat != NVL(:NEW.MaSuat, -1)
      AND (:NEW.GioBatDau < GioKetThuc AND :NEW.GioKetThuc > GioBatDau);

    IF v_count > 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Lỗi lịch chiếu: Phòng chiếu đã có suất chiếu khác hoạt động trong khung giờ này!');
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_TINH_TONG_TIEN_VE
AFTER INSERT OR UPDATE OR DELETE ON VE
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        IF :NEW.TrangThai <> 'Huy' THEN
            UPDATE DON_DAT_VE 
            SET TongTien = TongTien + :NEW.GiaVe
            WHERE MaDon = :NEW.MaDon AND NgayDat = :NEW.NgayDat;
        END IF;
    ELSIF UPDATING THEN
        IF :OLD.TrangThai <> 'Huy' AND :NEW.TrangThai = 'Huy' THEN
            UPDATE DON_DAT_VE 
            SET TongTien = GREATEST(TongTien - :OLD.GiaVe, 0)
            WHERE MaDon = :NEW.MaDon AND NgayDat = :NEW.NgayDat;
        END IF;
    ELSIF DELETING THEN
        IF :OLD.TrangThai <> 'Huy' THEN
            UPDATE DON_DAT_VE 
            SET TongTien = GREATEST(TongTien - :OLD.GiaVe, 0)
            WHERE MaDon = :OLD.MaDon AND NgayDat = :OLD.NgayDat;
        END IF;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_AUDIT_THANH_TOAN
AFTER INSERT ON THANH_TOAN
FOR EACH ROW
BEGIN
    INSERT INTO NHAT_KY (BangTacDong, HanhDong, NoiDung)
    VALUES ('THANH_TOAN', 'INSERT', 'Đơn ' || :NEW.MaDon || ' thanh toán thành công ' || :NEW.SoTien || ' VNĐ qua ' || :NEW.PhuongThuc);
END;
