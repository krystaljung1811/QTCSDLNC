-- 18. VIEW V_GHE_TRONG
CREATE OR REPLACE VIEW V_GHE_TRONG AS
SELECT 
    sc.MaSuat,
    p.TenPhim,
    pc.TenPhong,
    g.MaGhe,
    g.HangGhe,
    g.SoGhe,
    g.LoaiGhe,
    ROUND(sc.GiaCoBan * (CASE WHEN g.LoaiGhe = 'VIP' THEN 1.2 WHEN g.LoaiGhe = 'Doi' THEN 1.5 ELSE 1.0 END), 0) AS GiaVeDuKien,
    CASE 
        WHEN v.MaVe IS NULL THEN 'Trong'
        WHEN v.TrangThai = 'Hop le' THEN 'DangGiuCho'
        WHEN v.TrangThai = 'Da dung' THEN 'DaDat'
        ELSE 'Trong'
    END AS TinhTrang
FROM SUAT_CHIEU sc
JOIN PHIM p ON sc.MaPhim = p.MaPhim
JOIN PHONG_CHIEU pc ON sc.MaPhong = pc.MaPhong
JOIN GHE g ON pc.MaPhong = g.MaPhong
LEFT JOIN VE v ON sc.MaSuat = v.MaSuat 
              AND g.MaGhe = v.MaGhe 
              AND v.TrangThai IN ('Hop le', 'Da dung');
/

