-- 20. PACKAGE BÁO CÁO PKG_BAOCAO (Tỷ lệ lấp đầy & Báo cáo động)
CREATE OR REPLACE PACKAGE PKG_BAOCAO AUTHID DEFINER AS
    FUNCTION TINH_TY_LE_LAP_DAY(p_ma_suat NUMBER) RETURN NUMBER;
    PROCEDURE BAO_CAO_DONG(
        p_table_name IN VARCHAR2,
        p_where_col  IN VARCHAR2,
        p_val        IN VARCHAR2
    );
END PKG_BAOCAO;
/

CREATE OR REPLACE PACKAGE BODY PKG_BAOCAO AS

    FUNCTION TINH_TY_LE_LAP_DAY(p_ma_suat NUMBER) RETURN NUMBER IS
        v_tong NUMBER := 0;
        v_ban  NUMBER := 0;
    BEGIN
        SELECT pc.SoGhe INTO v_tong
        FROM SUAT_CHIEU sc JOIN PHONG_CHIEU pc ON sc.MaPhong = pc.MaPhong
        WHERE sc.MaSuat = p_ma_suat;

        SELECT COUNT(*) INTO v_ban
        FROM VE WHERE MaSuat = p_ma_suat AND TrangThai IN ('Hop le', 'Da dung');

        IF v_tong = 0 THEN RETURN 0; END IF;
        RETURN ROUND((v_ban / v_tong) * 100, 2);
    END TINH_TY_LE_LAP_DAY;

    PROCEDURE BAO_CAO_DONG(
        p_table_name IN VARCHAR2,
        p_where_col  IN VARCHAR2,
        p_val        IN VARCHAR2
    ) IS
        v_sql VARCHAR2(1000);
        v_count NUMBER;
    BEGIN
        v_sql := 'SELECT COUNT(*) FROM ' || DBMS_ASSERT.ENQUOTE_NAME(p_table_name) ||
                 ' WHERE ' || DBMS_ASSERT.ENQUOTE_NAME(p_where_col) || ' = :val';
        
        EXECUTE IMMEDIATE v_sql INTO v_count USING p_val;
        DBMS_OUTPUT.PUT_LINE('Thống kê trên ' || p_table_name || ' theo ' || p_where_col || ' [' || p_val || ']: ' || v_count || ' bản ghi.');
    END BAO_CAO_DONG;

END PKG_BAOCAO;
