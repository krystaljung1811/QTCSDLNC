CREATE OR REPLACE PACKAGE BODY PKG_DATVE AS

    FUNCTION TINH_GIA_VE_CHUAN(p_suat NUMBER, p_ghe NUMBER) RETURN NUMBER IS
        v_gia_cb NUMBER;
        v_loai   VARCHAR2(20);
    BEGIN
        SELECT GiaCoBan INTO v_gia_cb FROM SUAT_CHIEU WHERE MaSuat = p_suat;
        SELECT LoaiGhe INTO v_loai FROM GHE WHERE MaGhe = p_ghe;
        RETURN ROUND(v_gia_cb * (CASE WHEN v_loai = 'VIP' THEN 1.2 WHEN v_loai = 'Doi' THEN 1.5 ELSE 1.0 END), 0);
    END TINH_GIA_VE_CHUAN;

    PROCEDURE DAT_VE_GIU_CHO(
        p_ma_kh       IN NUMBER,
        p_ma_nv       IN NUMBER,
        p_ma_suat     IN NUMBER,
        p_ma_ghe      IN NUMBER,
        p_ma_don      OUT NUMBER,
        p_ma_ve       OUT NUMBER,
        p_gia_tinh    OUT NUMBER,
        p_status_code OUT NUMBER,
        p_message     OUT VARCHAR2
    ) IS
        v_ngay_dat TIMESTAMP := SYSTIMESTAMP;
        v_het_han  TIMESTAMP := SYSTIMESTAMP + INTERVAL '10' MINUTE;
        v_count    NUMBER;
    BEGIN
        p_gia_tinh := TINH_GIA_VE_CHUAN(p_ma_suat, p_ma_ghe);

        SELECT COUNT(*) INTO v_count
        FROM VE v
        JOIN DON_DAT_VE d ON v.MaDon = d.MaDon AND v.NgayDat = d.NgayDat
        WHERE v.MaSuat = p_ma_suat 
          AND v.MaGhe = p_ma_ghe 
          AND (v.TrangThai = 'Da dung' OR (v.TrangThai = 'Hop le' AND d.ThoiGianHetHanHold > SYSTIMESTAMP));

        IF v_count > 0 THEN
            p_status_code := 409;
            p_message := 'Ghế này đã có người đặt hoặc đang giữ chỗ!';
            RETURN;
        END IF;

        INSERT INTO DON_DAT_VE (MaKH, MaNV, NgayDat, TrangThai, TongTien, ThoiGianHetHanHold)
        VALUES (p_ma_kh, p_ma_nv, v_ngay_dat, 'Giu cho', 0, v_het_han)
        RETURNING MaDon INTO p_ma_don;

        INSERT INTO VE (MaDon, NgayDat, MaSuat, MaGhe, GiaVe, TrangThai)
        VALUES (p_ma_don, v_ngay_dat, p_ma_suat, p_ma_ghe, p_gia_tinh, 'Hop le')
        RETURNING MaVe INTO p_ma_ve;

        COMMIT;
        p_status_code := 200;
        p_message := 'Giữ chỗ thành công. Hết hạn sau 10 phút.';

    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            ROLLBACK;
            p_status_code := 409;
            p_message := 'Xung đột đồng thời: Ghế vừa được giao dịch bởi phiên khác!';
        WHEN OTHERS THEN
            ROLLBACK;
            p_status_code := 500;
            p_message := 'Lỗi cơ sở dữ liệu: ' || SQLERRM;
    END DAT_VE_GIU_CHO;

    PROCEDURE THEM_GHE_VAO_DON(
        p_ma_don      IN NUMBER,
        p_ngay_dat    IN TIMESTAMP,
        p_ma_suat     IN NUMBER,
        p_ma_ghe      IN NUMBER,
        p_ma_ve       OUT NUMBER,
        p_gia_tinh    OUT NUMBER,
        p_status_code OUT NUMBER,
        p_message     OUT VARCHAR2
    ) IS
        v_ngay_dat TIMESTAMP;
    BEGIN
        -- Lấy chính xác NgayDat gốc từ DON_DAT_VE để đảm bảo FK_VE_DON luôn khớp tuyệt đối
        SELECT NgayDat INTO v_ngay_dat FROM DON_DAT_VE WHERE MaDon = p_ma_don;

        p_gia_tinh := TINH_GIA_VE_CHUAN(p_ma_suat, p_ma_ghe);

        INSERT INTO VE (MaDon, NgayDat, MaSuat, MaGhe, GiaVe, TrangThai)
        VALUES (p_ma_don, v_ngay_dat, p_ma_suat, p_ma_ghe, p_gia_tinh, 'Hop le')
        RETURNING MaVe INTO p_ma_ve;

        COMMIT;
        p_status_code := 200;
        p_message := 'Đã thêm ghế vào đơn hàng thành công.';
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            ROLLBACK;
            p_status_code := 409;
            p_message := 'Ghế này đã có người chọn!';
        WHEN NO_DATA_FOUND THEN
            ROLLBACK;
            p_status_code := 404;
            p_message := 'Không tìm thấy đơn đặt vé tương ứng!';
        WHEN OTHERS THEN
            ROLLBACK;
            p_status_code := 500;
            p_message := 'Lỗi thêm ghế: ' || SQLERRM;
    END THEM_GHE_VAO_DON;

    PROCEDURE XAC_NHAN_THANH_TOAN(
        p_ma_don      IN NUMBER,
        p_ngay_dat    IN TIMESTAMP,
        p_phuong_thuc IN VARCHAR2,
        p_so_tien     IN NUMBER,
        p_status_code OUT NUMBER,
        p_message     OUT VARCHAR2
    ) IS
        v_tong_tien NUMBER;
        v_trang_thai VARCHAR2(20);
        v_het_han   TIMESTAMP;
        v_ngay_dat  TIMESTAMP := p_ngay_dat;
    BEGIN
        IF v_ngay_dat IS NULL THEN
            SELECT NgayDat INTO v_ngay_dat FROM DON_DAT_VE WHERE MaDon = p_ma_don AND ROWNUM = 1;
        END IF;

        SELECT TongTien, TrangThai, ThoiGianHetHanHold, NgayDat
        INTO v_tong_tien, v_trang_thai, v_het_han, v_ngay_dat
        FROM DON_DAT_VE
        WHERE MaDon = p_ma_don
        FOR UPDATE;

        IF v_trang_thai <> 'Giu cho' THEN
            p_status_code := 400;
            p_message := 'Đơn hàng không ở trạng thái chờ thanh toán!';
            ROLLBACK;
            RETURN;
        END IF;

        IF SYSTIMESTAMP > v_het_han THEN
            p_status_code := 400;
            p_message := 'Đơn hàng đã hết hạn giữ chỗ!';
            ROLLBACK;
            RETURN;
        END IF;

        IF p_so_tien < v_tong_tien THEN
            p_status_code := 400;
            p_message := 'Số tiền thanh toán (' || p_so_tien || ') không đủ với tổng tiền đơn (' || v_tong_tien || ')!';
            ROLLBACK;
            RETURN;
        END IF;

        UPDATE DON_DAT_VE SET TrangThai = 'Da TT' WHERE MaDon = p_ma_don;
        UPDATE VE SET TrangThai = 'Da dung' WHERE MaDon = p_ma_don;

        INSERT INTO THANH_TOAN (MaDon, NgayDat, PhuongThuc, SoTien, TrangThai)
        VALUES (p_ma_don, v_ngay_dat, p_phuong_thuc, p_so_tien, 'Thanh cong');

        COMMIT;
        p_status_code := 200;
        p_message := 'Xác nhận thanh toán thành công.';
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            ROLLBACK;
            p_status_code := 404;
            p_message := 'Không tìm thấy thông tin đơn đặt vé!';
        WHEN OTHERS THEN
            ROLLBACK;
            p_status_code := 500;
            p_message := 'Lỗi thanh toán: ' || SQLERRM;
    END XAC_NHAN_THANH_TOAN;

    PROCEDURE HUY_VE(
        p_ma_don      IN NUMBER,
        p_ngay_dat    IN TIMESTAMP,
        p_status_code OUT NUMBER,
        p_message     OUT VARCHAR2
    ) IS
    BEGIN
        UPDATE DON_DAT_VE SET TrangThai = 'Huy' WHERE MaDon = p_ma_don;
        UPDATE VE SET TrangThai = 'Huy' WHERE MaDon = p_ma_don;

        COMMIT;
        p_status_code := 200;
        p_message := 'Hủy vé thành công, ghế đã được nhả lại.';
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            p_status_code := 500;
            p_message := 'Lỗi hủy vé: ' || SQLERRM;
    END HUY_VE;

END PKG_DATVE;
